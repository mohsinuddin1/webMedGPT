// Use English as fallback for missing locales
const defaultLocale = 'en';

export function getUITranslation(lang: string, key: keyof typeof uiTranslations['en']) {
  const normalized = (lang || defaultLocale).toLowerCase();
  const langKey = (normalized in uiTranslations ? normalized : defaultLocale) as keyof typeof uiTranslations;
  return uiTranslations[langKey][key] || uiTranslations[defaultLocale][key];
}
